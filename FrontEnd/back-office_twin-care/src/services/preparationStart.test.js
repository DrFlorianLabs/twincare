import test from 'node:test'
import assert from 'node:assert/strict'

import {
  buildPatientInvitationLink,
  copyPatientInvitationLink,
  createPatientInvitationExecutor,
  createPreparationCreationExecutor,
  createPreparationRequestTracker,
  isCreationRequestId,
  isNormalizedPreparationDraft,
  normalizePreparationDraft,
  parseUnambiguousLocalDateTime,
  patientPreparationBaseUrl,
  PREPARATION_START_OUTCOME
} from './preparationStart.js'

const TOKEN = 'A'.repeat(43)

test('normalizes the minimal future preparation without adding client-owned scope', () => {
  const preparation = normalizePreparationDraft({
    patientReference: '  patient-synthetic-42 ',
    appointmentReference: '  appointment-synthetic-7 ',
    scheduledAt: '2026-08-23T10:30'
  }, Date.parse('2026-08-22T10:00:00Z'))
  assert.deepEqual(preparation, {
    patientReference: 'patient-synthetic-42',
    appointmentReference: 'appointment-synthetic-7',
    scheduledAt: new Date('2026-08-23T10:30').toISOString()
  })
  assert.equal(isNormalizedPreparationDraft(preparation), true)
  assert.equal(isNormalizedPreparationDraft({
    ...preparation,
    patientReference: ' patient-synthetic-42 '
  }), false)
})

test('rejects an invalid, past or control-character preparation draft', () => {
  const now = Date.parse('2026-08-22T10:00:00Z')
  for (const draft of [
    { patientReference: '', scheduledAt: '2026-08-23T10:30' },
    { patientReference: 'patient\nreference', scheduledAt: '2026-08-23T10:30' },
    { patientReference: 'patient', appointmentReference: 'x'.repeat(129), scheduledAt: '2026-08-23T10:30' },
    { patientReference: 'patient', scheduledAt: '2026-08-22T09:30' },
    { patientReference: 'patient', scheduledAt: 'not-a-date' }
  ]) {
    assert.equal(normalizePreparationDraft(draft, now), null)
  }
})

test('accepts only an absolute safe patient base URL without query, fragment or credentials', () => {
  assert.equal(patientPreparationBaseUrl('https://patient.example/preparation'), 'https://patient.example/preparation')
  assert.equal(patientPreparationBaseUrl('http://localhost:5174/'), 'http://localhost:5174/')
  for (const value of [
    '',
    '/patient',
    'javascript:alert(1)',
    'http://patient.example/preparation',
    'https://patient.example/?',
    'https://patient.example/#',
    'https://user:secret@patient.example/',
    'https://patient.example/?source=staff',
    'https://patient.example/#token=old'
  ]) {
    assert.equal(patientPreparationBaseUrl(value), '')
  }
})

test('builds the invitation exclusively in the URL fragment', () => {
  const link = buildPatientInvitationLink('https://patient.example/preparation', TOKEN)
  const url = new URL(link)
  assert.equal(url.search, '')
  assert.equal(url.hash, `#token=${TOKEN}`)
  assert.equal(url.pathname, '/preparation')
  assert.throws(() => buildPatientInvitationLink('https://patient.example/', 'invalid'))
})

test('copies only a valid invitation link through the explicitly provided clipboard', async () => {
  const writes = []
  const link = buildPatientInvitationLink('https://patient.example/', TOKEN)
  await copyPatientInvitationLink(link, { writeText: async value => writes.push(value) })
  assert.deepEqual(writes, [link])
  await assert.rejects(copyPatientInvitationLink('https://patient.example/', { writeText: async () => {} }))
  await assert.rejects(copyPatientInvitationLink(
    `https://patient.example/?leak=1#token=${TOKEN}`,
    { writeText: async () => {} }
  ))
  await assert.rejects(copyPatientInvitationLink(
    `https://patient.example/?#token=${TOKEN}`,
    { writeText: async () => {} }
  ))
})

test('recognizes the UUID request identifiers generated by the browser', () => {
  assert.equal(isCreationRequestId('2f3de63b-692d-4c20-8a48-c7ec01b95b21'), true)
  assert.equal(isCreationRequestId('not-a-request-id'), false)
})

test('keeps one request identifier and exact payload across an explicit creation retry', () => {
  const identifiers = [
    '2f3de63b-692d-4c20-8a48-c7ec01b95b21',
    '3f3de63b-692d-4c20-8a48-c7ec01b95b22'
  ]
  const tracker = createPreparationRequestTracker(() => identifiers.shift())
  const normalized = normalizePreparationDraft({
    patientReference: 'patient-synthetic',
    scheduledAt: '2099-01-02T10:30'
  })
  const capturedPayload = tracker.payload(normalized)
  assert.equal(tracker.current(), '2f3de63b-692d-4c20-8a48-c7ec01b95b21')
  assert.equal(tracker.current(), '2f3de63b-692d-4c20-8a48-c7ec01b95b21')
  tracker.markAmbiguous()
  assert.equal(tracker.isAmbiguous(), true)
  assert.equal(tracker.current(), '2f3de63b-692d-4c20-8a48-c7ec01b95b21')
  assert.equal(tracker.payload(), capturedPayload)
  tracker.reset()
  assert.equal(tracker.isAmbiguous(), false)
  assert.equal(tracker.current(), '3f3de63b-692d-4c20-8a48-c7ec01b95b22')
  assert.throws(() => createPreparationRequestTracker(() => 'unsafe').current())
  assert.throws(() => createPreparationRequestTracker().payload({ scheduledAt: 'invalid' }))
})

test('rejects missing and ambiguous daylight-saving local times', () => {
  const previousTimeZone = process.env.TZ
  process.env.TZ = 'Europe/Paris'
  try {
    assert.equal(parseUnambiguousLocalDateTime('2026-03-29T02:30'), null)
    assert.equal(parseUnambiguousLocalDateTime('2026-10-25T02:30'), null)
    assert.equal(
      parseUnambiguousLocalDateTime('2026-03-29T03:30')?.toISOString(),
      '2026-03-29T01:30:00.000Z'
    )
  } finally {
    if (previousTimeZone === undefined) delete process.env.TZ
    else process.env.TZ = previousTimeZone
  }
})

test('creation execution is single-flight and ignores a response after its scope changes', async () => {
  let resolveCreation
  let requestCount = 0
  const pending = new Promise(resolve => { resolveCreation = resolve })
  const execute = createPreparationCreationExecutor(async () => {
    requestCount += 1
    await pending
    return { caseId: 'case-a' }
  })
  let current = true
  const context = {
    scope: 'cabinet-a\u0000request-a',
    stillApplies: () => current,
    operationArguments: ['cabinet-a', 'request-a', {}]
  }

  const first = execute(context)
  const duplicate = await execute(context)
  assert.equal(duplicate.outcome, PREPARATION_START_OUTCOME.ALREADY_RUNNING)
  assert.equal(requestCount, 1)

  current = false
  resolveCreation()
  assert.equal((await first).outcome, PREPARATION_START_OUTCOME.STALE)
})

test('invitation execution never retries an ambiguous failure', async () => {
  let requestCount = 0
  const execute = createPatientInvitationExecutor(async () => {
    requestCount += 1
    throw new Error('Network failure')
  })

  await assert.rejects(execute({
    scope: 'cabinet-a\u0000case-a',
    stillApplies: () => true,
    operationArguments: ['cabinet-a', 'case-a']
  }))
  assert.equal(requestCount, 1)
})
